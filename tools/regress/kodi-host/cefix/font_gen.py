"""font_gen.py <kodi tree> <out>: <out>/font_pieces.cpp, the code of xbmc/utils/FontUtils.cpp that reads the family
names of a font file in memory (GetFamilyNameFromSfnt() and GetFontFamilyNames(buffer, names)), word for word, in its
namespace, with the headers of Kodi it needs replaced by those of the test (font_stubs.h: the log and the charset
converter); the file's own loading of a path and the rest are left out (they need Kodi's file system)."""
import os
import re
import sys

src = open(os.path.join(sys.argv[1], 'xbmc/utils/FontUtils.cpp'), encoding='utf-8').read()
start = src.index('namespace\n{\n// \\brief Get font family from SFNT table entries')
m = re.search(r'^bool GetFontFamilyNames\(const std::vector<uint8_t>& buffer, std::set<std::string>& familyNames\)\n\{',
              src[start:], re.M)
if not m:
    sys.exit('no GetFontFamilyNames(buffer, familyNames) in FontUtils.cpp')
i = start + m.end() - 1
depth = 0
while True:
    if src[i] == '{':
        depth += 1
    elif src[i] == '}':
        depth -= 1
        if depth == 0:
            break
    i += 1
os.makedirs(sys.argv[2], exist_ok=True)
with open(os.path.join(sys.argv[2], 'font_pieces.cpp'), 'w', encoding='utf-8') as out:
    out.write('// generated by font_gen.py from xbmc/utils/FontUtils.cpp\n#include "font_stubs.h"\n\n'
              '#include <algorithm>\n#include <cstdint>\n#include <set>\n#include <string>\n#include <vector>\n\n'
              '#include <ft2build.h>\n\n#include FT_FREETYPE_H\n#include FT_SFNT_NAMES_H\n#include FT_TRUETYPE_IDS_H\n\n'
              'namespace KODI::UTILS::FONT\n{\n\n')
    out.write(src[start:i + 1])
    out.write('\n\n} // namespace KODI::UTILS::FONT\n')
print('font_pieces.cpp: %d lines of FontUtils.cpp' % src[start:i + 1].count('\n'))
