"""Write gles_shim.c: the OpenGL ES functions a program calls, each one forwarding to the pointer that
eglGetProcAddress() gives for it. A build host has Mesa's EGL but no libGLESv2 to link against.

usage: gles_shim.py <header>... < names of the undefined gl* symbols, one per line > gles_shim.c
"""
import re
import sys


def main():
    protos = {}
    for path in sys.argv[1:]:
        text = open(path, encoding='utf-8').read()
        for m in re.finditer(r"GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(gl\w+)\s*\((.*?)\);", text, re.S):
            ret, name, params = m.group(1).strip(), m.group(2), " ".join(m.group(3).split())
            protos.setdefault(name, (ret, params))
    out = ["/* Generated by gles_shim.py: OpenGL ES entry points through eglGetProcAddress(). */",
           "#include <EGL/egl.h>", "#include <GLES3/gl32.h>", "#include <GLES2/gl2ext.h>", ""]
    missing = []
    for name in sorted(set(line.strip() for line in sys.stdin if line.strip())):
        if name not in protos:
            missing.append(name)
            continue
        ret, params = protos[name]
        args = []
        if params != "void":
            for p in params.split(","):
                args.append(re.search(r"(\w+)\s*(\[\d*\])?\s*$", p.strip()).group(1))
        call = "f(%s)" % ", ".join(args)
        out.append("%s GL_APIENTRY %s(%s)" % (ret, name, params))
        out.append("{")
        out.append("    static %s (GL_APIENTRY *f)(%s);" % (ret, params))
        out.append("    if (!f) f = (%s (GL_APIENTRY *)(%s))eglGetProcAddress(\"%s\");" % (ret, params, name))
        out.append("    %s%s;" % ("" if ret == "void" else "return ", call))
        out.append("}")
        out.append("")
    if missing:
        sys.exit("no prototype for: " + " ".join(missing))
    print("\n".join(out))


if __name__ == '__main__':
    main()
